package cert

// This file contains tests for error paths in CreateCertificate.
// We use a pragmatic approach that tests what's reasonably testable
// without over-engineering the production code.
//
// Coverage achieved:
// - ecdsa.GenerateKey error: ✅ Tested by mocking rand.Reader
// - rand.Int error: ✅ Tested by mocking rand.Reader with partial failure
// - privateKey.PublicKey.ECDH() error: ❌ Not testable (P256 ECDH conversion cannot fail)
// - x509.CreateCertificate error: ❌ Not testable without major refactoring
//
// The two untestable error paths represent defensive programming for
// extremely rare system-level failures that would require significant
// refactoring to test, with minimal benefit.

import (
	"crypto/rand"
	"crypto/tls"
	"errors"
	"io"
	"testing"

	"github.com/stretchr/testify/assert"
)

// mockFailingReader implements io.Reader that always returns an error
type mockFailingReader struct{}

func (m mockFailingReader) Read(p []byte) (n int, err error) {
	return 0, errors.New("mocked random source failure")
}

// TestCreateCertificate_ErrorPaths tests the error handling paths in CreateCertificate
func TestCreateCertificate_ErrorPaths(t *testing.T) {
	// Test 1: ecdsa.GenerateKey error (line 32-33)
	// We temporarily replace rand.Reader to trigger the error
	t.Run("GenerateKey_Error", func(t *testing.T) {
		oldReader := rand.Reader
		rand.Reader = mockFailingReader{}
		defer func() { rand.Reader = oldReader }()

		cert, err := CreateCertificate("test", "org", "DE", "CN")
		assert.Error(t, err)
		assert.Equal(t, tls.Certificate{}, cert)
		assert.Contains(t, err.Error(), "mocked random source failure")
	})

	// Test 2: rand.Int error (line 56-57)
	// This uses a custom mock that fails only after successful key generation
	t.Run("RandInt_Error", func(t *testing.T) {
		oldReader := rand.Reader
		rand.Reader = &mockPartialFailingReader{failAfterNCalls: 2, realReader: oldReader} // Fail on 3rd call (after key gen)
		defer func() { rand.Reader = oldReader }()

		cert, err := CreateCertificate("test", "org", "DE", "CN")
		assert.Error(t, err)
		assert.Equal(t, tls.Certificate{}, cert)
		assert.Contains(t, err.Error(), "random int generation failure")
	})

	// Test 3: x509.CreateCertificate error (line 73-74)
	// This requires refactoring to test properly, but we can document the limitation
	t.Run("CreateCertificate_Error_Documentation", func(t *testing.T) {
		// Note: x509.CreateCertificate errors are difficult to trigger with valid inputs
		// from CreateCertificate. The function validates inputs before calling x509.CreateCertificate.
		// This error path would only occur in cases of:
		// - System resource exhaustion
		// - Invalid certificate constraints that pass initial validation
		// - Cryptographic operation failures at the system level
		
		// For now, we document this limitation and accept that this specific error path
		// is covered by integration testing rather than unit testing.
		t.Skip("x509.CreateCertificate error path cannot be reliably tested without refactoring")
	})

	// Test 4: privateKey.PublicKey.ECDH() error (line 38-39)
	t.Run("ECDH_Error_Documentation", func(t *testing.T) {
		// Note: The ECDH() method on ECDSA P256 keys generated by the standard library
		// cannot fail in practice. This error check is defensive programming.
		// The Go crypto library guarantees that P256 ECDSA keys can be converted to ECDH format.
		
		// This error path would only be triggered by:
		// - Memory corruption
		// - Using a modified crypto library
		// - Hardware failures
		
		// We document this as a limitation of unit testing.
		t.Skip("ECDH conversion for P256 keys cannot fail with standard library")
	})
}

// mockPartialFailingReader fails after N successful calls
type mockPartialFailingReader struct {
	failAfterNCalls int
	callCount       int
	realReader      io.Reader
}

func (m *mockPartialFailingReader) Read(p []byte) (n int, err error) {
	m.callCount++
	if m.callCount > m.failAfterNCalls {
		return 0, errors.New("random int generation failure")
	}
	// Use real random for initial calls
	return m.realReader.Read(p)
}

